#!/usr/bin/env python3
"""Turn the GLSL files and the shapes file into one C file of string constants.

usage: embed.py [--min] out.c files...
--min strips comments, indentation and blank lines (used for the release build).
x.glsl becomes shader_x; any other file keeps its name (shapes.txt becomes shapes_txt).
"""
import re
import sys

args = sys.argv[1:]
minify = False
if args and args[0] == "--min":
    minify = True
    args = args[1:]
out, files = args[0], args[1:]


def shrink(src: str) -> str:
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    lines = []
    for line in src.split("\n"):
        line = re.sub(r"//.*", "", line).strip()
        if not line:
            continue
        if not line.startswith("#"):
            line = re.sub(r"\s+", " ", line)
            line = re.sub(r" ?([-+*/=<>!&|,;:?(){}\[\]]) ?", r"\1", line)
        lines.append(line)
    return "\n".join(lines) + "\n"


def shrink_text(src: str) -> str:  # shapes file: '#' comments
    lines = [re.sub(r"\s+", " ", line.split("#")[0]).strip() for line in src.split("\n")]
    return "\n".join(line for line in lines if line) + "\n"


def c_string(src: str) -> str:
    rows = []
    for line in src.split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        rows.append(f'"{esc}\\n"')
    return "\n".join(rows)


with open(out, "w") as o:
    o.write("// generated by tools/embed.py\n")
    for path in files:
        base = path.split("/")[-1]
        glsl = base.endswith(".glsl")
        name = ("shader_" + base[:-5] if glsl else base).replace(".", "_")
        with open(path) as f:
            src = f.read()
        if minify:
            src = shrink(src) if glsl else shrink_text(src)
        o.write(f"const char {name}[] =\n{c_string(src)};\n")
        o.write(f"const int {name}_len = sizeof {name} - 1;\n")
